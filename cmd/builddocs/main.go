	b.WriteString("```lua\nonon.theme.elements.row_selected.draw = function(canvas, box, state)\n  canvas:default()\n  canvas:rect(0, 5, 3, box.h - 10, \"accent\", 1.5) -- a bar at the left\nend\n```\n")
