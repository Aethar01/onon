	b.WriteString("```lua\nonon.theme = {\n  base = \"birch\",  -- start from a built-in theme; the default is " + config.DefaultTheme + "\n  accent = \"#335533\",\n  alt = { accent = \"#88aa88\" },\n  font = { family = \"Iosevka\", size = 14 },\n}\n```\n\n")
	b.WriteString("`require` searches the configuration file's directory first, so a theme can live in a file of its own beside `config.lua`. Have it return its table, as `themes/forest.lua` holding `return { accent = \"#2f5d3a\" }`, and apply it with `onon.theme = require(\"themes.forest\")`; dots in the name are directories, and `require(\"forest\")` would load `forest.lua`.\n\n")
	b.WriteString("`:theme` lists the built-in themes and the theme files, each named for its file: those in `themes/` beside `config.lua`, then those in each directory plugins are searched for with `themes` in place of `plugins`, as `/usr/lib/onon/themes` and `~/.config/onon/themes` on Linux. Directories under each of them are searched too, so a theme can be kept in a directory of its own with the shaders and images it draws with, as `themes/liquid/liquid.lua` beside `liquid.glsl`. Where two directories have a file of the same name, the first wins, and within one the file nearest it. `:theme` shows each one as it is selected: Enter keeps it, Esc puts back the theme before, and `:theme <name>` switches straight to one. A file named for a built-in theme is left out. The theme chosen is remembered and applied before `config.lua` runs, so what `config.lua` changes field by field, as `onon.theme.accent = \"#335533\"` does, changes the chosen theme too; assigning `onon.theme` whole replaces it, and `:theme` then says that a theme it picks lasts only until onon restarts.\n\n")
	b.WriteString("Fields left out keep the base theme's values. Assign a preset by name with `onon.theme = \"birch\"`, or a single field with `onon.theme.accent = \"#335533\"`; at runtime use `:set theme=birch` or `:set theme.accent=#335533`. Built-in themes: " + codeList(config.ThemeNames()) + ". `onon.themes.<name>` gives a copy of one to change. Fields and element properties this version does not know are skipped with a warning, so a theme written for a newer version still loads; `:set` refuses them.\n\n")
	b.WriteString("Colours are `\"#RRGGBB\"` or `{ r, g, b }`. The `alt` table holds the colours used in alternate-color mode, toggled with `:colors`, and has the same colour fields as the theme. The `font` table picks the UI font; with neither `family` nor `path` set it is the system's interface font.\n\n")
