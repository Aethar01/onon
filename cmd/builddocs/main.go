func main() {
	check := flag.Bool("check", false, "check generated files without writing")
	flag.Parse()
	if err := config.ValidateReferenceMetadata(); err != nil {
		fatal(err)
	}
	luaRefs := config.LuaReferences()
	luaDocs, err := loadLuaFunctionDocs()
	if err != nil {
		fatal(err)
	}
	if err := validateLuaFunctionDocs(luaRefs, luaDocs); err != nil {
		fatal(err)
	}
	reference := renderReference(luaRefs, luaDocs)
	outputs := map[string][]byte{
		"docs/reference.md":  []byte(reference),
		"config.example.lua": []byte(renderExampleConfig()),
	}
	for path, content := range outputs {
		if *check {
			existing, err := os.ReadFile(path)
			if errors.Is(err, os.ErrNotExist) && path == "docs/reference.md" {
				// The application repository ignores the generated reference; the
				// documentation site generates it during its build.
				continue
			}
			if err != nil || !bytes.Equal(existing, content) {
				fatal(fmt.Errorf("%s is stale; run go generate ./...", path))
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			fatal(err)
		}
		if err := os.WriteFile(path, content, 0o644); err != nil {
			fatal(err)
		}
	}
}

